import fs from 'node:fs';

const data = JSON.parse(fs.readFileSync('evidence/game-post-gpr-domain-coverage-c4/population-matching-probes.json', 'utf8'));
const checks = [];
const check = (name, condition) => checks.push({ name, pass: Boolean(condition) });

check('candidate-c4', data.candidate.includes('Population / Matching'));
check('gpr8-not-admitted', data.routeAdmission.gpr8 === false);
check('numbered-foundation-not-admitted', data.routeAdmission.newNumberedFoundation === false);
check('next-gpr-unknown', data.routeAdmission.nextGpr === 'UNKNOWN');
check('next-practical-unknown', data.routeAdmission.nextPracticalRoute === 'UNKNOWN');
check('next-foundation-unknown', data.routeAdmission.nextFoundation === 'UNKNOWN');
check('eight-candidate-deletions', data.candidateDeletion.length >= 8);
check('population-primitive-rejected', data.candidateDeletion.some(x => x.candidate === 'Population' && x.verdict.includes('REJECT')));
check('queue-primitive-rejected', data.candidateDeletion.some(x => x.candidate === 'Queue' && x.verdict.includes('REJECT')));
check('matchmaking-ontology-rejected', data.candidateDeletion.some(x => x.candidate === 'Matchmaking' && x.verdict.includes('REJECT')));
check('good-match-rejected', data.candidateDeletion.some(x => x.candidate === 'FairGoodMatch' && x.verdict.includes('REJECT')));
check('synthetic-population-rejected', data.candidateDeletion.some(x => x.candidate === 'SyntheticPopulation' && x.verdict.includes('REJECT')));
check('sixteen-probes', data.probes.length >= 16);
check('empty-queue-causal-reality', data.probes.some(x => x.id === 'C4-F1' && x.result.includes('AvailablePlayOpportunitySet')));
check('pairing-policy-relative', data.probes.some(x => x.id === 'C4-F2' && x.result.includes('PopulationState != Pairing')));
check('bye-separates-practice-and-instance', data.probes.some(x => x.id === 'C4-F3' && x.result.includes('NotParticipantInPractice')));
check('team-pairing-not-lineup', data.probes.some(x => x.id === 'C4-F4' && x.result.includes('FinalInternalGameComposition')));
check('proposal-not-instance', data.probes.some(x => x.id === 'C4-F5' && x.result.includes('MatchProposal != GameInstanceConstitution')));
check('overlap-proposals-not-final', data.probes.some(x => x.id === 'C4-F6' && x.result.includes('FinalSelectedOpportunity')));
check('good-match-objective-relative', data.probes.some(x => x.id === 'C4-F7' && x.result.includes('GoodMatchByIdentity')));
check('team-formation-cross-domain', data.probes.some(x => x.id === 'C4-F8' && x.result.includes('CrossDomain')));
check('network-feasibility-separated', data.probes.some(x => x.id === 'C4-F9' && x.result.includes('NetworkFeasibility')));
check('role-scarcity-not-headcount', data.probes.some(x => x.id === 'C4-F11' && x.result.includes('PopulationCount')));
check('synthetic-filler-no-primitive', data.probes.some(x => x.id === 'C4-F12' && x.result.includes('new Game foundation kind')));
check('matchmaking-term-polysemy', data.probes.some(x => x.id === 'C4-F13' && x.result.includes('MatchmakingLabel')));
check('persistent-world-no-matching-necessity', data.probes.some(x => x.id === 'C4-F14' && x.result.includes('MatchmakingNecessity')));
check('population-drift-reduces-to-gdf2', data.probes.some(x => x.id === 'C4-F15' && x.reduction.some(v => v.includes('GDF2'))));
check('integrity-not-absorbed', data.probes.some(x => x.id === 'C4-F16' && x.reduction.some(v => v.includes('integrity'))));
check('opportunity-view-survives-practically', data.residualPattern.status.includes('PRACTICAL_RESEARCH_ABSTRACTION'));
check('seven-stage-separation', data.residualPattern.stages.length === 7);
check('proposal-instance-anticollapse', data.residualPattern.antiCollapse.includes('MatchProposal != GameInstance'));
check('selected-instance-anticollapse', data.residualPattern.antiCollapse.includes('SelectedOpportunity != ConstitutedInstanceByIdentity'));
check('c1-downstream-owner-explicit', Array.isArray(data.ownership.C1) && data.ownership.C1.some(v => v.includes('GameInstance constitution')));
check('network-runtime-owner-explicit', Array.isArray(data.ownership.NetworkRuntime) && data.ownership.NetworkRuntime.length >= 4);
check('general-matching-owner-explicit', Array.isArray(data.ownership.GeneralMatchingMechanismDesign) && data.ownership.GeneralMatchingMechanismDesign.length >= 4);
check('no-game-foundation-survives', data.foundationVerdict === 'NO_INDEPENDENT_GAME_FOUNDATION_RESPONSIBILITY_SURVIVES');
check('strong-practical-gap-no-gpr', data.practicalVerdict.includes('NO_GPR_ADMISSION'));
check('agent-era-no-new-population-primitive', data.agentEraVerdict.includes('NO_NEW_POPULATION_PRIMITIVE'));
check('all-reopen-negative', Object.values(data.reopenAudit).every(v => v === 'NOT_TRIGGERED'));
check('c1-survives', data.relativeUpdate.C1.startsWith('SURVIVES'));
check('c2-reduced', data.relativeUpdate.C2.startsWith('REDUCED'));
check('c3-reduced', data.relativeUpdate.C3.startsWith('REDUCED'));
check('c4-reduced', data.relativeUpdate.C4.startsWith('REDUCED'));
check('classification-cross-cutting', data.finalClassification.startsWith('CROSS_CUTTING'));
check('classification-c1-downstream', data.finalClassification.includes('DOWNSTREAM_CONSTITUTION_OWNED_BY_C1'));
check('classification-not-foundation', data.finalClassification.includes('NOT_GENUINELY_NEW_GAME_FOUNDATION'));
check('classification-not-route-selected', data.finalClassification.includes('NOT_ROUTE_SELECTED'));

for (const c of checks) console.log(`${c.pass ? 'PASS' : 'FAIL'} ${c.name}`);
const failed = checks.filter(c => !c.pass);
console.log(`SUMMARY ${checks.length - failed.length}/${checks.length} passed`);
if (failed.length) process.exit(1);
